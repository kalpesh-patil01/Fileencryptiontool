package com.fileencryption.servlet;

import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;

import javax.servlet.ServletException;
import javax.servlet.annotation.MultipartConfig;
import javax.servlet.annotation.WebServlet;
import javax.servlet.http.HttpServlet;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;
import javax.servlet.http.Part;

import com.fileencryption.service.FileEncryptionException;
import com.fileencryption.service.FileEncryptionService;
import com.fileencryption.util.FileUtils;

/**
 * Handles POST /encrypt : receives a file + password, returns "<name>.enc" as a download.
 *
 * @MultipartConfig lets the servlet read multipart/form-data (file uploads).
 * Tomcat rejects uploads bigger than maxFileSize / maxRequestSize.
 */

@WebServlet("/encrypt")
@MultipartConfig(
        fileSizeThreshold = FileUtils.UPLOAD_MEMORY_THRESHOLD,
        maxFileSize = FileUtils.MAX_FILE_SIZE,
        maxRequestSize = FileUtils.MAX_FILE_SIZE + FileUtils.MAX_REQUEST_OVERHEAD)
public class EncryptionServlet extends HttpServlet {

    private static final long serialVersionUID = 1L;
    private static final int MIN_PASSWORD_LENGTH = 8;

    /** Opening /encrypt in the browser (GET) just goes back to the home page. */
    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response) throws IOException {
        response.sendRedirect(request.getContextPath() + "/");
    }

    @Override
    protected void doPost(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {

        // The service holds no per-user data, so a new object per request is simple and thread-safe
        FileEncryptionService encryptionService = new FileEncryptionService();

        request.setCharacterEncoding("UTF-8"); // so non-English passwords are read correctly

        Part filePart = null;
        Path tempFile = null;
        try {
            // ---- 1. Validate the request ----
            String contentType = request.getContentType();
            if (contentType == null || !contentType.toLowerCase().startsWith("multipart/form-data")) {
                FileUtils.showError(request, response, HttpServletResponse.SC_BAD_REQUEST,
                        "Invalid request. Please use the form on the home page.");
                return;
            }

            // getPart() throws IllegalStateException if the upload is bigger than the limits
            filePart = request.getPart("file");
            if (filePart == null || filePart.getSize() <= 0) {
                FileUtils.showError(request, response, HttpServletResponse.SC_BAD_REQUEST,
                        "Please choose a file to encrypt. The file is missing or empty.");
                return;
            }
            if (filePart.getSize() > FileUtils.MAX_FILE_SIZE) {
                FileUtils.showError(request, response, HttpServletResponse.SC_REQUEST_ENTITY_TOO_LARGE,
                        "The file is too large. The maximum size is 10 MB.");
                return;
            }

            String password = request.getParameter("password");
            String confirmPassword = request.getParameter("confirmPassword");
            if (password == null || password.isEmpty()) {
                FileUtils.showError(request, response, HttpServletResponse.SC_BAD_REQUEST,
                        "Please enter a password.");
                return;
            }
            if (password.length() < MIN_PASSWORD_LENGTH) {
                FileUtils.showError(request, response, HttpServletResponse.SC_BAD_REQUEST,
                        "The password is too short. Use at least " + MIN_PASSWORD_LENGTH + " characters.");
                return;
            }
            if (!password.equals(confirmPassword)) {
                FileUtils.showError(request, response, HttpServletResponse.SC_BAD_REQUEST,
                        "The password and the confirmation do not match.");
                return;
            }

            // Only used for the download name. The browser's file name is never used as a server path.
            String downloadName = FileUtils.buildEncryptedFileName(filePart.getSubmittedFileName());

            // ---- 2. Encrypt into a temporary file ----
            // If encryption fails, nothing has been sent to the browser yet, so we can show an error.
            tempFile = Files.createTempFile("fenc-enc-", ".tmp"); // name is generated by Java, not by the user
            char[] passwordChars = password.toCharArray();
            try (InputStream in = filePart.getInputStream();
                 OutputStream out = Files.newOutputStream(tempFile)) {
                encryptionService.encrypt(in, out, passwordChars);
            } finally {
                java.util.Arrays.fill(passwordChars, '\0'); // wipe the password from memory
            }

            // ---- 3. Send the encrypted file ----
            FileUtils.sendDownload(response, tempFile, downloadName);

        } catch (IllegalStateException e) {
            // Thrown by Tomcat when the upload is bigger than maxFileSize / maxRequestSize
            if (!response.isCommitted()) {
                FileUtils.showError(request, response, HttpServletResponse.SC_REQUEST_ENTITY_TOO_LARGE,
                        "The file is too large. The maximum size is 10 MB.");
            }
        } catch (FileEncryptionException e) {
            if (!response.isCommitted()) {
                FileUtils.showError(request, response, HttpServletResponse.SC_INTERNAL_SERVER_ERROR,
                        e.getMessage());
            }
        } catch (IOException | ServletException e) {
            // Details stay on the server (no password, no stack trace for the user)
            log("Encryption request failed: " + e.getClass().getSimpleName());
            if (!response.isCommitted()) {
                FileUtils.showError(request, response, HttpServletResponse.SC_BAD_REQUEST,
                        "The upload could not be read. Please try again.");
            }
        } finally {
            // Always clean up: temp output file and the uploaded part Tomcat may have stored on disk
            FileUtils.deleteQuietly(tempFile);
            if (filePart != null) {
                try {
                    filePart.delete();
                } catch (IOException e) {
                    // ignore - Tomcat also removes upload files when the request ends
                }
            }
        }
    }
}
